#!/usr/bin/env python3
"""Generate sounddata.h: embedded 8-bit unsigned 8000 Hz mono sound samples.

Sound order matches the SND_* enum in sound.h and the sound server table:
0 explode, 1 firetorp, 2 shield, 3 torphit, 4 explode_big, 5 ddloo, 6 warp, 7 smart.
"""
import os
import sys

NAMES = ["explode", "firetorp", "shield", "torphit",
         "explode_big", "ddloo", "warp", "smart"]

def main():
    srcdir = os.path.join(os.path.dirname(__file__), "..", "sounds")
    blobs = []
    for name in NAMES:
        with open(os.path.join(srcdir, name + ".raw"), "rb") as f:
            blobs.append(f.read())

    out = []
    out.append("/* Generated by mksounddata.py from sounds/*.raw (8-bit unsigned, 8000 Hz). */")
    out.append("/* Sound 0..7 = SND_EXPLOSION .. SND_SMART (see sound.h). */")
    for i, (name, blob) in enumerate(zip(NAMES, blobs)):
        out.append(f"static const unsigned char sound_{i}_{name}[] = {{")
        chunks = [", ".join(str(b) for b in blob[j:j + 60])
                  for j in range(0, len(blob), 60)]
        out.extend("    " + c + "," for c in chunks)
        out.append("};")
    out.append("")
    out.append("static const struct { const unsigned char *data; unsigned long len; } "
               "sounds_web[8] = {")
    for i, (name, blob) in enumerate(zip(NAMES, blobs)):
        out.append(f"    /* {name} */")
        out.append(f"    {{ sound_{i}_{name}, {len(blob)} }},")
    out.append("};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
