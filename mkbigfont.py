#!/usr/bin/env python3
"""Generate web/bigfontdata.h: bitmap glyphs for the game's "big" font.

The original X11 build renders W_BigFont with the XLFD font
"-adobe-helvetica-bold-r-normal--34-*" (see libsprite/defs.h BIG_FONT).
On modern fontconfig systems that resolves to Nimbus Sans Bold (URW's
metric-compatible Helvetica) at 34px.  We rasterize that exact font so the
web build shows the same large "LEVEL N" banner as the original.

Usage: python3 web/mkbigfont.py web/bigfontdata.h
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_CANDIDATES = [
    "/usr/share/fonts/gsfonts/NimbusSans-Bold.otf",
    "/usr/share/fonts/type1/urw-base35/NimbusSans-Bold.otf",
    "/usr/share/fonts/liberation/LiberationSans-Bold.ttf",
]
SIZE = 34           # XLFD pixel size of BIG_FONT
THRESH = 128        # 1-bit rendering, as an X bitmap font
OX, OY = 32, 64     # pen origin on the scratch canvas (OY = baseline row)
PAD = 16


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "web/bigfontdata.h"
    fontpath = next((p for p in FONT_CANDIDATES if os.path.exists(p)), None)
    if fontpath is None:
        sys.exit("mkbigfont: none of the candidate fonts found: %s"
                 % ", ".join(FONT_CANDIDATES))
    font = ImageFont.truetype(fontpath, SIZE)
    ascent, descent = font.getmetrics()
    height = ascent + descent

    rows = bytearray()
    meta = []
    maxadv = 0
    for ch in range(32, 127):
        c = chr(ch)
        adv = int(round(font.getlength(c)))
        maxadv = max(maxadv, adv)
        img = Image.new("L", (OX + 2 * PAD, OY - ascent + height + 2 * PAD), 0)
        ImageDraw.Draw(img).text((OX, OY - ascent), c, font=font, fill=255)
        a = __import__("numpy").asarray(img)
        ys, xs = __import__("numpy").nonzero(a >= THRESH)
        if len(xs) == 0:
            meta.append((adv, 0, 0, 0, len(rows)))
            continue
        left_off = xs.min() - OX              # ink left relative to the pen
        w = xs.max() - xs.min() + 1
        h = ys.max() - ys.min() + 1
        dy = ys.min() - (OY - ascent)         # ink top row inside the cell
        rowofs = len(rows)
        for r in range(h):
            nbytes = (w + 7) // 8
            for b in range(nbytes):
                v = 0
                for bit in range(8):
                    col = b * 8 + bit
                    if col < w and a[ys.min() + r, xs.min() + col] >= THRESH:
                        v |= 0x80 >> bit
                rows.append(v)
        meta.append((adv, w, h, dy, rowofs))

    lines = [
        "/* Generated by web/mkbigfont.py - do not edit by hand.",
        " *",
        " * Bitmap glyphs for the 'big' font (W_BigFont): Adobe Helvetica",
        " * Bold, XLFD pixel size %d, as the original X11 build loads it" % SIZE,
        " * (BIG_FONT in libsprite/defs.h).  Rasterized from %s."
        % os.path.basename(fontpath),
        " *",
        " * Cell: BIGFONT_ASCENT above + BIGFONT_DESCENT below the baseline.",
        " * Glyph bitmaps hold the ink rows only; dy is the row of the ink's",
        " * top inside the cell.  Rows are packed MSB-first (leftmost pixel",
        " * = bit 7), ceil(w/8) bytes per row.",
        " */",
        "#ifndef BIGFONTDATA_H",
        "#define BIGFONTDATA_H",
        "",
        "#define BIGFONT_ASCENT  %d" % ascent,
        "#define BIGFONT_DESCENT %d" % descent,
        "#define BIGFONT_HEIGHT  %d" % height,
        "#define BIGFONT_MAXADV  %d" % maxadv,
        "",
        "typedef struct {",
        "    unsigned char adv;      /* advance width, px */",
        "    unsigned char w;        /* bitmap width, px (0 = blank) */",
        "    unsigned char h;        /* bitmap height, rows */",
        "    unsigned char dy;       /* ink top row within the cell */",
        "    unsigned short rowofs;  /* byte offset into bigfont_rows */",
        "} bigglyph_t;",
        "",
        "static const bigglyph_t bigfont_glyph[95] = {",
    ]
    for (adv, w, h, dy, rowofs), ch in zip(meta, range(32, 127)):
        name = {32: "space", 39: "'"} .get(ch, chr(ch))
        lines.append("    /* %s */" % name)
        lines.append("    {%d, %d, %d, %d, %d}," % (adv, w, h, dy, rowofs))
    lines.append("};")
    lines.append("")
    lines.append("static const unsigned char bigfont_rows[] = {")
    for i in range(0, len(rows), 16):
        chunk = rows[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines += ["", "#endif /* BIGFONTDATA_H */", ""]

    with open(out, "w") as f:
        f.write("\n".join(lines))
    # cell height = ascent+descent; ink rows are a subset
    print("wrote %s: %d glyphs, %d row bytes, metrics %d/%d (ascent/descent)"
          % (out, len(meta), len(rows), ascent, descent))
    # sanity: measure "LEVEL 5" the way draw_text will place it
    pen = 0
    for c in "LEVEL 5":
        adv, w, h, dy, rowofs = meta[ord(c) - 32]
        pen += adv
    print("sanity: 'LEVEL 5' advance = %d px (cap height 25 in the "
          "original screenshot)" % pen)


if __name__ == "__main__":
    main()
